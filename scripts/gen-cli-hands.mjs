#!/usr/bin/env node
// Regenerates cli/hands-art.mjs: the hero's hands (public/hero-hands.png) as a
// small grid of density levels (0-9) the CLI draws with an ASCII ramp. Run by
// hand when the artwork changes — the output is committed, so building the CLI
// does not need sharp.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const SRC = path.join(ROOT, "public/hero-hands.png");
const OUT = path.join(ROOT, "cli/hands-art.mjs");
/** Terminal cells are about twice as tall as wide. */
const CELL_ASPECT = 1.45;
const SIZES = { wide: 76, narrow: 44 };

const { data, info } = await sharp(SRC).greyscale().raw().toBuffer({ resolveWithObject: true });

// Bounding box of the lit area, like AsciiHands.analyse().
let [x0, y0, x1, y1] = [info.width, info.height, 0, 0];
for (let y = 0; y < info.height; y++) {
  for (let x = 0; x < info.width; x++) {
    if (data[y * info.width + x] > 60) {
      x0 = Math.min(x0, x);
      x1 = Math.max(x1, x);
      y0 = Math.min(y0, y);
      y1 = Math.max(y1, y);
    }
  }
}
const box = { left: x0, top: y0, width: x1 - x0 + 1, height: y1 - y0 + 1 };

const art = {};
for (const [name, cols] of Object.entries(SIZES)) {
  const h = Math.max(6, Math.round(((box.height / box.width) * cols) / CELL_ASPECT));
  const cells = await sharp(SRC).extract(box).greyscale().resize(cols, h, { fit: "fill", kernel: "lanczos3" }).raw().toBuffer();
  const lines = [];
  for (let y = 0; y < h; y++) {
    let line = "";
    for (let x = 0; x < cols; x++) {
      const l = cells[y * cols + x] / 255;
      line += l < 0.07 ? "0" : String(Math.min(9, 1 + Math.floor(l ** 0.8 * 8.99)));
    }
    lines.push(line);
  }
  art[name] = lines;
}

const body = Object.entries(art)
  .map(([name, lines]) => `  ${name}: [\n${lines.map((l) => `    "${l}",`).join("\n")}\n  ],`)
  .join("\n");
fs.writeFileSync(
  OUT,
  `// Generated by scripts/gen-cli-hands.mjs from public/hero-hands.png — do not edit.
// Each character is a density level 0-9 (0 = empty) of one terminal cell.
export const HANDS = {
${body}
};
`,
);
console.log(`wrote ${path.relative(ROOT, OUT)}: ${Object.entries(art).map(([n, l]) => `${n} ${l[0].length}×${l.length}`).join(", ")}`);
