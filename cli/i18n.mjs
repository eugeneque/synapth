export const DICT = { en, ru, zh };

/** A translator bound to a language getter, so a language change applies at once. */
export function createT(getLang) {
  return (key, vars) => {
    const raw = DICT[getLang()]?.[key] ?? en[key] ?? key;
    return vars ? raw.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? "")) : raw;
  };
}
