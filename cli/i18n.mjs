/**
 * Synapth CLI strings: English, Russian, Chinese. Only what a person reads in
 * the terminal is translated — server errors, `--json` output and everything
 * the local MCP server says to an agent stay English (agents and logs read it).
 * `{name}` placeholders are filled by `t(key, { name })`; a key missing in a
 * language falls back to English.
 */

export const LANGS = ["en", "ru", "zh"];
export const LANG_NAMES = { en: "English", ru: "Русский", zh: "中文" };

/** The language the OS suggests (LC_ALL → LC_MESSAGES → LANG), English when unsure. */
export function detectLang(env = process.env) {
  const raw = String(env.LC_ALL || env.LC_MESSAGES || env.LANG || "").toLowerCase();
  if (raw.startsWith("ru")) return "ru";
  if (raw.startsWith("zh")) return "zh";
  return "en";
}

